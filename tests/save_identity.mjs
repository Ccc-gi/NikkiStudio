import assert from 'node:assert/strict';
import {prepareSaveIdentities,reserveSaveIdentities} from '../frontend/save_identity.js';
import {writeGameSave} from '../frontend/workspace_game_files.js';
const row=(id,type,attach=0)=>({instanceID:id,furnitureInfo:{cfg_item_id:type,attach_id:attach,group_id:0,colors:[2],trans:{position:{x:1,y:2,z:3}}},unknown:{keep:true}});
const current={NeedRestore:true,Snapshots:[row(1,10),row(2,20),row(100,30)]};
const input={NeedRestore:true,Snapshots:[row(1,10),row(2,99),row(50,40,2)]};
const before=structuredClone(input);
const fixed=prepareSaveIdentities(input,current);
assert.deepEqual(input,before,'preparation must not mutate working document');
assert.deepEqual(fixed.data.Snapshots.map(r=>r.instanceID),[1,101,102]);
assert.equal(fixed.data.Snapshots[2].furnitureInfo.attach_id,101);
assert.equal(fixed.data.Snapshots[1].furnitureInfo.cfg_item_id,99);
assert.equal(prepareSaveIdentities(fixed.data,fixed.data).changed,0);
assert.deepEqual(prepareSaveIdentities({Snapshots:{}},{Snapshots:{}}).data,{Snapshots:{}});
const memory=new Map(),storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
reserveSaveIdentities(storage,'BUILD_SAVEDATA_1.json',input,current);
assert.equal(reserveSaveIdentities(storage,'BUILD_SAVEDATA_1.json',input,current).floor,104,'failed or cancelled writes cannot reuse reserved ids');
assert.throws(()=>prepareSaveIdentities({Snapshots:[row(1,10),row(1,20)]},current),/重复/);
assert.throws(()=>prepareSaveIdentities({Snapshots:[row(0,10)]},current),/无效/);
assert.throws(()=>prepareSaveIdentities(input,current,{floor:2147483647}),/范围/);
assert.throws(()=>reserveSaveIdentities({getItem:()=>null,setItem:()=>{throw Error('quota');}},'x',input,current),/quota/);
const raw=JSON.stringify(current),written=[];let disk=raw;
const target={name:'BUILD_SAVEDATA_1.json',getFile:async()=>({text:async()=>disk}),createWritable:async()=>({write:async t=>written.push(t),close:async()=>{},abort:async()=>{}})};
const backup={createWritable:async()=>({write:async t=>assert.equal(t,raw),close:async()=>{}})};
const dir={getDirectoryHandle:async()=>({getFileHandle:async()=>backup})};
await writeGameSave(dir,target,JSON.stringify(fixed.data),raw);
assert.equal(written.length,1);
disk='changed';
await assert.rejects(writeGameSave(dir,target,JSON.stringify(fixed.data),raw),/修改/);
assert.equal(written.length,1);
disk=raw;
const racingDir={getDirectoryHandle:async()=>({getFileHandle:async()=>({createWritable:async()=>({write:async()=>{},close:async()=>{disk='changed during backup';}})})})};
await assert.rejects(writeGameSave(racingDir,target,JSON.stringify(fixed.data),raw),/备份期间/);
assert.equal(written.length,1);
console.log('PASS: identity reconciliation, reference preservation, persistent reservations and guarded writes');
