import assert from 'node:assert/strict';
import {SaveDocument} from '../frontend/save_document.js';
const row=id=>({instanceID:id,furnitureInfo:{cfg_item_id:1,trans:{position:{x:0,y:0,z:0}},attach_id:0}});
const doc=new SaveDocument({Snapshots:[row(100)]});
doc.add(2,{x:0,y:0,z:0});
doc.undo();
doc.add(3,{x:0,y:0,z:0});
assert.equal(doc.rows.at(-1).instanceID,102);
const copied=doc.duplicateMany([0,1]);
const ceiling=doc.rows.at(-1).instanceID;
doc.removeMany(copied);
doc.add(4,{x:0,y:0,z:0});
assert.equal(doc.rows.at(-1).instanceID,ceiling+1);
doc.addItems([row(0),row(0),row(0)]);
const presetCeiling=doc.rows.at(-1).instanceID;
doc.undo();
doc.add(5,{x:0,y:0,z:0});
assert.equal(doc.rows.at(-1).instanceID,presetCeiling+1);
console.log('PASS: add, copy and preset ids are never reused after delete or undo');
